namespace StockApi.Data;

public static class SaleStatus
{
    public const string Paid = "Paid";
    public const string Loan = "Loan";
    public const string PartiallyPaid = "PartiallyPaid";
}

public class Customer
{
    public Guid Id { get; set; }
    public string FullName { get; set; } = "";
    public string Phone { get; set; } = "";     // normalized, unique
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
}

public class SalesSession
{
    public Guid Id { get; set; }
    public Guid SalespersonId { get; set; }
    public DateOnly SessionDate { get; set; }
    public DateTime StartedAt { get; set; }
    public DateTime? CheckedOutAt { get; set; }   // NULL = still open
}

public class Sale
{
    public Guid Id { get; set; }
    public string InvoiceNo { get; set; } = null!;  // generated by the PostgreSQL sequence
    public Guid SessionId { get; set; }
    public Guid SalespersonId { get; set; }
    public AppUser? Salesperson { get; set; }
    public Guid? CustomerId { get; set; }
    public Customer? Customer { get; set; }
    public bool WantsReceipt { get; set; }          // true = sold at price WITH VAT
    public decimal Subtotal { get; set; }
    public decimal VatTotal { get; set; }
    public decimal Total { get; set; }
    public decimal AmountPaid { get; set; }         // kept in sync by a DB trigger
    public string Status { get; set; } = SaleStatus.Loan;   // kept in sync by a DB trigger
    public bool IsLoan { get; set; }
    public DateTime CreatedAt { get; set; }
    public List<SaleItem> Items { get; set; } = new();
    public List<Payment> Payments { get; set; } = new();
}

public class SaleItem
{
    public Guid Id { get; set; }
    public Guid SaleId { get; set; }
    public Guid ProductId { get; set; }
    public string ProductSku { get; set; } = "";
    public string ProductName { get; set; } = "";
    public int Quantity { get; set; }
    public decimal UnitPrice { get; set; }          // without VAT
    public decimal UnitCost { get; set; }
    public decimal VatAmount { get; set; }          // line VAT (0 when no receipt)
    public decimal LineTotal { get; set; }
}

public class Payment
{
    public Guid Id { get; set; }
    public Guid SaleId { get; set; }
    public int PaymentMethodId { get; set; }
    public PaymentMethod? PaymentMethod { get; set; }
    public int? PaymentProviderId { get; set; }
    public PaymentProvider? PaymentProvider { get; set; }
    public string? TransactionRef { get; set; }
    public string? ReceiptImagePath { get; set; }
    public decimal Amount { get; set; }
    public Guid ReceivedBy { get; set; }
    public DateTime PaidAt { get; set; }
    public bool IsLoanRepayment { get; set; }
}
